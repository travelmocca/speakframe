import { afterEach, expect, it } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { Store } from '../src/lib/store';
import { beijingDay, calendarYear, activityLevel } from '../src/lib/activity';
const stores: Store[] = [], dirs: string[] = [];
afterEach(() => { stores.splice(0).forEach(db => db.close()); dirs.splice(0).forEach(dir => rmSync(dir, { recursive: true, force: true })); });
it('uses Beijing midnight, counts every saved round, and excludes other accounts, future or deleted records', () => {
  const dir = mkdtempSync(join(tmpdir(), 'activity-')); dirs.push(dir); const db = new Store(dir); stores.push(db);
  const a = db.register('13800000001', 'test-password'), b = db.register('13800000002', 'test-password');
  const p = db.createPractice(a.id, 'opinion'); db.updatePractice(a.id, p.id, '日记录测试');
  const first = db.addAttempt(a.id, p.id, { filename: '1.wav', mime: 'audio/wav', duration: 2 });
  db.db.prepare("UPDATE attempts SET createdAt=?,status='done' WHERE id=?").run(Date.parse('2026-10-31T15:59:59.999Z'), first.id);
  const second = db.addAttempt(a.id, p.id, { filename: '2.wav', mime: 'audio/wav', duration: 2 });
  db.db.prepare("UPDATE attempts SET createdAt=?,status='failed' WHERE id=?").run(Date.parse('2026-10-31T16:00:00Z'), second.id);
  db.addReflection(a.id, p.id, '感悟不计入表达次数'); db.createPractice(a.id);
  const other = db.createPractice(b.id); db.addAttempt(b.id, other.id, { filename: 'private.wav', mime: 'audio/wav', duration: 2 });
  const future = db.createPractice(a.id); const futureAttempt = db.addAttempt(a.id, future.id, { filename: 'future.wav', mime: 'audio/wav', duration: 2 });
  db.db.prepare('UPDATE attempts SET createdAt=? WHERE id=?').run(Date.parse('2026-11-03T00:00:00Z'), futureAttempt.id);
  const now = Date.parse('2026-11-02T00:00:00Z');
  expect(db.activityDays(a.id, now)).toMatchObject([{ date: '2026-10-31', count: 1 }, { date: '2026-11-01', count: 1 }]);
  const day = db.activityForDate(a.id, '2026-11-01', now); expect(day).toHaveLength(1); expect(day[0].attemptId).toBe(second.id); expect(day[0].sequence).toBe(2);
  expect(db.activityForDate(b.id, '2026-11-01', now).some(row => row.practiceId === p.id)).toBe(false);
  expect(() => db.activityForDate(a.id, '2026-02-30', now)).toThrow();
  const beforeRevision = db.activityDays(a.id, now).find(day => day.date === '2026-11-01')!.revision;
  expect(db.activityDays(a.id, now).find(day => day.date === '2026-11-01')!.revision).toBe(beforeRevision);
  db.db.prepare('DELETE FROM attempts WHERE id=?').run(second.id);
  const replacement = db.addAttempt(a.id, p.id, { filename: 'replacement.wav', mime: 'audio/wav', duration: 2 });
  db.db.prepare('UPDATE attempts SET createdAt=? WHERE id=?').run(Date.parse('2026-10-31T16:00:00Z'), replacement.id);
  const replacedDay = db.activityDays(a.id, now).find(day => day.date === '2026-11-01')!;
  expect(replacedDay.count).toBe(1); expect(replacedDay.revision).not.toBe(beforeRevision);
  db.deletePractice(a.id, p.id); expect(db.activityDays(a.id, now)).toEqual([]);
});
it('builds a leap-year calendar and keeps future days distinct from zero recordings', () => {
  expect(beijingDay(Date.parse('2026-10-31T16:00:00Z'))).toBe('2026-11-01');
  const leap = calendarYear(2024, '2024-06-01');
  expect(leap.cells.filter(cell => cell.date)).toHaveLength(366);
  expect(leap.cells.some(cell => cell.date === '2024-02-29')).toBe(true);
  expect(leap.cells.find(cell => cell.date === '2024-06-02')?.future).toBe(true);
  expect(calendarYear(2026, '2026-11-01').cells.filter(cell => cell.date)).toHaveLength(365);
  expect([0, 1, 2, 3, 4, 6, 7, 100].map(activityLevel)).toEqual([0, 1, 2, 2, 3, 3, 4, 4]);
});
