import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';
const origin = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
const headers = { Origin: origin };
test('API ownership, real audio validation, duplicate account, login, range and deletion', async ({ playwright }) => {
  const a = await playwright.request.newContext({ baseURL: origin, extraHTTPHeaders: headers });
  const b = await playwright.request.newContext({ baseURL: origin, extraHTTPHeaders: headers });
  const phoneA = '136' + Date.now().toString().slice(-8), phoneB = '135' + Date.now().toString().slice(-8);
  const password = 'Api-test-password';
  expect((await a.post('/api/auth/register', { data: { phone: phoneA, password } })).status()).toBe(200);
  expect((await b.post('/api/auth/register', { data: { phone: phoneB, password } })).status()).toBe(200);
  expect((await a.post('/api/auth/register', { data: { phone: phoneA, password } })).status()).toBe(409);
  const cookie = (await a.storageState()).cookies.find(c => c.name === 'expression_session');
  expect(cookie?.httpOnly).toBe(true);
  const { practice } = await (await a.post('/api/practices', { data: { scenario: 'opinion' } })).json();
  const url = `/api/practices/${practice.id}`;
  const privateWorkspace = await (await b.get('/api/workspace')).json();
  expect(privateWorkspace.practices).toEqual([]); expect(privateWorkspace.issues).toEqual([]); expect(privateWorkspace.activity.days).toEqual([]);
  expect((await b.get('/api/activity?date=not-a-date')).status()).toBe(400);
  expect((await b.get(url)).status()).toBe(404);
  expect((await b.patch(url, { data: { title: 'x', goal: 'x' } })).status()).toBe(404);
  expect((await b.delete(url)).status()).toBe(404);
  expect((await b.post(`${url}/topic-voice`)).status()).toBe(404);
  expect((await b.post(`${url}/reflection-voice`)).status()).toBe(404);
  expect((await b.post(`${url}/reflections`, { data: { text: '越权感悟' } })).status()).toBe(404);
  expect((await a.post(`${url}/reflections`, { data: { text: '  ' } })).status()).toBe(400);
  expect((await a.post(`${url}/reflections`, { data: { text: '接口验收感悟' } })).status()).toBe(201);
  expect((await (await a.get(url)).json()).practice.reflections).toHaveLength(1);
  expect((await a.post(`${url}/topic-voice`, { multipart: { other: 'missing audio' } })).status()).toBe(400);
  expect((await a.patch(url, { data: { title: '接口验收', goal: '核实录音保存和账号隔离' } })).status()).toBe(200);
  expect((await a.post(`${url}/attempts`, { multipart: { audio: { name: 'fake.wav', mimeType: 'audio/wav', buffer: Buffer.from('not an audio file') } } })).status()).toBe(400);
  const uploaded = await a.post(`${url}/attempts`, { multipart: { audio: { name: 'real.wav', mimeType: 'audio/wav', buffer: readFileSync('outputs/omni-audio-samples/audio/01.wav') } } });
  expect(uploaded.status()).toBe(201);
  expect((await a.post(`${url}/topic-voice`)).status()).toBe(400);
  const { attempt } = await uploaded.json();
  expect(attempt.duration).toBeGreaterThan(1);
  const calendar = (await (await a.get('/api/workspace')).json()).activity;
  expect(calendar.days.reduce((sum: number, day: { count: number }) => sum + day.count, 0)).toBe(1);
  expect((await (await a.get(`/api/activity?date=${calendar.today}`)).json()).attempts).toHaveLength(1);
  expect((await (await b.get(`/api/activity?date=${calendar.today}`)).json()).attempts).toEqual([]);
  const audioUrl = `/api/attempts/${attempt.id}/audio`;
  expect((await b.get(audioUrl)).status()).toBe(404);
  const full = await a.get(audioUrl); expect(full.status()).toBe(200);
  const range = await a.get(audioUrl, { headers: { Range: 'bytes=0-99' } }); expect(range.status()).toBe(206); expect((await range.body()).length).toBe(100);
  expect((await a.get(audioUrl, { headers: { Range: 'bytes=999999999-' } })).status()).toBe(416);
  expect((await a.delete(url, { headers: { Origin: 'https://foreign.example' } })).status()).toBe(403);
  expect((await a.delete(url)).status()).toBe(200);
  expect((await a.get(audioUrl)).status()).toBe(404);
  await a.post('/api/auth/logout'); expect((await a.get('/api/me')).status()).toBe(401);
  expect((await a.post('/api/auth/login', { data: { phone: phoneA, password: 'incorrect' } })).status()).toBe(401);
  expect((await a.post('/api/auth/login', { data: { phone: phoneA, password } })).status()).toBe(200);
  expect((await a.get('/api/me')).status()).toBe(200);
  await a.dispose(); await b.dispose();
});
